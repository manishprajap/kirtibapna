// Scans /public/products for extra photos named "<slug>-2.jpg", "<slug>-3.jpg", … and writes
// src/lib/gallery.generated.ts. Runs automatically before `npm run dev` / `npm run build`.
//   <slug>.jpg      -> main photo (already used)
//   <slug>-2.jpg    -> back photo (shown on hover in the shop grid)
//   <slug>-3.jpg …  -> more photos (side, detail) – all shown in the product-page gallery
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "public/products");
const src = fs.readFileSync(path.join(root, "src/lib/products.ts"), "utf8");
const slugs = [...src.matchAll(/slug:\s*"([^"]+)"/g)].map((m) => m[1]);
const files = fs.readdirSync(dir);
const exts = /\.(jpe?g|png|webp|avif)$/i;

const out = {};
for (const slug of slugs) {
  const extras = files
    .map((f) => {
      const m = f.match(new RegExp(`^${slug.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}-(\\d+)(\\.[a-z]+)$`, "i"));
      return m && exts.test(f) ? { n: Number(m[1]), f } : null;
    })
    .filter(Boolean)
    .sort((a, b) => a.n - b.n)
    .map((x) => `/products/${x.f}`);
  if (extras.length) out[slug] = extras;
}

fs.writeFileSync(
  path.join(root, "src/lib/gallery.generated.ts"),
  `// AUTO-GENERATED by scripts/gen-gallery.mjs – do not edit.\nexport const extraImages: Record<string, string[]> = ${JSON.stringify(out, null, 2)};\n`
);
console.log(`gallery: ${Object.keys(out).length} product(s) with extra images`);

// ---- Home-page banners: public/banners/banner-1.jpg, banner-2.jpg, … (any of jpg/png/webp/avif) ----
const bdir = path.join(root, "public/banners");
const banners = fs.existsSync(bdir)
  ? fs
      .readdirSync(bdir)
      .filter((f) => /^banner-.*\.(jpe?g|png|webp|avif)$/i.test(f))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
      .map((f) => `/banners/${f}`)
  : [];
fs.writeFileSync(
  path.join(root, "src/lib/banners.generated.ts"),
  `// AUTO-GENERATED by scripts/gen-gallery.mjs – do not edit.\nexport const banners: string[] = ${JSON.stringify(banners, null, 2)};\n`
);
console.log(`banners: ${banners.length} slide(s)`);
