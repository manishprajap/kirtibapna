
// Scans /public/products for extra photos named "<slug>-2.jpg", "<slug>-3.jpg", …
// Writes src/lib/gallery.generated.ts.
// Runs automatically before npm run dev / npm run build.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const root = path.resolve(__dirname, "..");

const dir = path.join(root, "public", "products");
const productsPath = path.join(root, "src", "lib", "products.ts");

if (!fs.existsSync(productsPath)) {
  throw new Error(`Products file not found: ${productsPath}`);
}

if (!fs.existsSync(dir)) {
  throw new Error(`Products folder not found: ${dir}`);
}

const src = fs.readFileSync(productsPath, "utf8");

const slugs = [...src.matchAll(/slug:\s*"([^"]+)"/g)].map((m) => m[1]);

const files = fs.readdirSync(dir);
const exts = /\.(jpe?g|png|webp|avif)$/i;

const out = {};

for (const slug of slugs) {
  const extras = files
    .map((f) => {
      const escapedSlug = slug.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const m = f.match(
        new RegExp(`^${escapedSlug}-(\\d+)(\\.[a-z]+)$`, "i")
      );

      return m && exts.test(f) ? { n: Number(m[1]), f } : null;
    })
    .filter(Boolean)
    .sort((a, b) => a.n - b.n)
    .map((x) => `/products/${x.f}`);

  if (extras.length) out[slug] = extras;
}

fs.writeFileSync(
  path.join(root, "src", "lib", "gallery.generated.ts"),
  `// AUTO-GENERATED by scripts/gen-gallery.mjs – do not edit.
export const extraImages: Record<string, string[]> = ${JSON.stringify(out, null, 2)};
`
);

console.log(
  `gallery: ${Object.keys(out).length} product(s) with extra images`
);

// ---- Home-page banners ----

const bdir = path.join(root, "public", "banners");

const banners = fs.existsSync(bdir)
  ? fs
      .readdirSync(bdir)
      .filter((f) => /^banner-.*\.(jpe?g|png|webp|avif)$/i.test(f))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
      .map((f) => `/banners/${f}`)
  : [];

fs.writeFileSync(
  path.join(root, "src", "lib", "banners.generated.ts"),
  `// AUTO-GENERATED by scripts/gen-gallery.mjs – do not edit.
export const banners: string[] = ${JSON.stringify(banners, null, 2)};
`
);

console.log(`banners: ${banners.length} slide(s)`);
