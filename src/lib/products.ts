import { extraImages } from "./gallery.generated";

export type Category = "Suits" | "Lehengas" | "Sarees" | "Co-ord Sets" | "Formal Sets" | "Dresses";

export interface Product {
  slug: string;
  name: string;
  category: Category;
  /** Extra categories the piece is also listed in (as on the original site). */
  alsoIn?: Category[];
  price: number;
  /** Original price. Equal to `price` when the item is not discounted. */
  mrp: number;
  /** Only set when the fabric is known. */
  fabric?: string;
  description: string;
  colors: { name: string; hex: string }[];
  sizes: string[];
  /** [main colour, darker shade] – tints the illustration when the photo is missing */
  palette: [string, string];
  tag?: "New" | "Bestseller" | "Sale";
  featured?: boolean;
  /** Set to true to mark the piece as sold out (hidden by the "In stock" filter). */
  soldOut?: boolean;
  care: string;
  /** Photo path. Put the file in /public/products (e.g. "/products/<slug>.jpg"). */
  image: string;
  /**
   * Extra photos (back, side, detail…). Put the files in /public/products and list them here,
   * e.g. images: ["/products/<slug>-2.jpg", "/products/<slug>-3.jpg"].
   * The FIRST extra image is shown on hover in the shop grid; all of them appear in the product-page gallery.
   */
  images?: string[];
}

/** Main photo + extra photos, in display order */
export const getGallery = (p: Product): string[] => [p.image, ...(p.images ?? [])];

